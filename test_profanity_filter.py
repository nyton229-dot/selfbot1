def run() -> None:
    failed: list[str] = []

    for msg in PROFANE_MESSAGES:
        found, censored = censor_text(msg)
        if not found:
            failed.append(f"ПРОПУЩЕН МАТ: {msg!r}")
        elif censored == msg:
            failed.append(f"МАТ НАЙДЕН, НО НЕ ЗАЦЕНЗУРЕН: {msg!r}")

    for msg in CLEAN_MESSAGES:
        if contains_profanity(msg):
            _, censored = censor_text(msg)
            failed.append(f"ЛОЖНОЕ СРАБАТЫВАНИЕ: {msg!r} -> {censored!r}")

    # Цензура сохраняет обычные слова.
    found, censored = censor_text("слушай, иди нахуй отсюда")
    assert found
    assert censored.startswith("слушай, иди ") and "нахуй" not in censored, censored

    # Повторный прогон зацензуренного текста не должен находить мат.
    assert not contains_profanity(censored), censored

    if failed:
        print(f"ПРОВАЛЕНО ({len(failed)}):")
        for line in failed:
            print("  " + line)
        raise SystemExit(1)

    total = len(PROFANE_MESSAGES) + len(CLEAN_MESSAGES)
    print(f"OK: все {total} проверок пройдены")


if __name__ == "__main__":
    run()
